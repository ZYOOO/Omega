const dictionaries: Record<UiLanguage, Record<string, string>> = {
  en: {},
  "zh-CN": zhCN
};

function normalizeUiLanguage(value: string | undefined | null): UiLanguage {
  return value === "zh-CN" || value === "zh" || value === "zh_CN" ? "zh-CN" : "en";
}

export function initialUiLanguage(): UiLanguage {
  if (typeof window === "undefined") return "en";
  return normalizeUiLanguage(window.localStorage.getItem(uiLanguageStorageKey));
}

export function translateUi(language: UiLanguage, key: string, params?: TranslationParams): string {
  const template = dictionaries[language][key] ?? key;
  if (!params) return template;
  return template.replace(/\{(\w+)\}/g, (match, name) => String(params[name] ?? match));
}

type I18nContextValue = {
  language: UiLanguage;
  t: (key: string, params?: TranslationParams) => string;
};

const I18nContext = createContext<I18nContextValue>({
  language: "en",
  t: (key, params) => translateUi("en", key, params)
});

export function I18nProvider({ language, children }: { language: UiLanguage; children: ReactNode }) {
  return (
    <I18nContext.Provider value={{ language, t: (key, params) => translateUi(language, key, params) }}>
      {children}
    </I18nContext.Provider>
  );
}

export function useI18n() {
  return useContext(I18nContext);
}

export function LanguageToggle({
  language,
  onLanguageChange
}: {
  language: UiLanguage;
  onLanguageChange: (language: UiLanguage) => void;
}) {
  const { t } = useI18n();
  return (
    <label className="language-toggle" aria-label={t("Language")}>
      <span className="sr-only">{t("Language")}</span>
      <select
        value={language}
        onChange={(event) => onLanguageChange(normalizeUiLanguage(event.currentTarget.value))}
        aria-label={t("Switch language")}
      >
        <option value="en">{t("English")}</option>
        <option value="zh-CN">{t("简体中文")}</option>
      </select>
    </label>
  );
}
